package io.github.ezequiel24123z.grindless.guidance;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonNull;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

import static io.github.ezequiel24123z.grindless.guidance.ResourceGuidance.*;
import static io.github.ezequiel24123z.grindless.sustainability.SustainabilityAnnotations.*;
import static io.github.ezequiel24123z.grindless.sustainability.SustainabilityModel.*;

/** Deterministic, closed schema shared by the generator and packaged-resource reader. */
public final class ResourceGuidanceJson {
    private static final Gson JSON = new GsonBuilder().serializeNulls().disableHtmlEscaping()
            .setPrettyPrinting().create();
    private static final Set<String> ENTRY_FIELDS = Set.of("resource", "resource_class", "side_stream_class",
            "first_use_tier", "first_renewable_tier", "canonical_route", "future_consumers", "handling",
            "recycling", "originating_catalyst", "uncertainty", "producers", "consumers", "sources");

    private ResourceGuidanceJson() {
    }

    public static Document prepare(Map<Resource, Entry> resources) {
        return new Document(SCHEMA_VERSION, fingerprint(payload(resources)), resources);
    }

    public static String write(Document document) {
        JsonArray resources = payload(document.resources());
        if (!fingerprint(resources).equals(document.contentSha256())) {
            throw new IllegalArgumentException("Resource guidance content fingerprint does not match");
        }
        return JSON.toJson(object("schema_version", document.schemaVersion(),
                "content_sha256", document.contentSha256(), "resources", resources)) + "\n";
    }

    /**
     * Only canonical generated bytes are accepted. Re-encoding also rejects duplicate fields,
     * duplicate resources, comments, coercions and unknown fields instead of accepting partial data.
     */
    public static Document read(String json) {
        json = json.replace("\r\n", "\n");
        JsonObject root = closed(JsonParser.parseString(json), Set.of("schema_version", "content_sha256", "resources"));
        int schema = integer(root.get("schema_version"));
        Map<Resource, Entry> resources = new TreeMap<>();
        for (JsonElement value : array(root.get("resources"))) {
            JsonObject row = closed(value, ENTRY_FIELDS);
            Resource resource = resource(row.get("resource"));
            List<FutureConsumer> future = new ArrayList<>();
            for (JsonElement candidate : array(row.get("future_consumers"))) {
                JsonObject consumer = closed(candidate, Set.of("tier", "system", "plan_reference"));
                future.add(new FutureConsumer(integer(consumer.get("tier")), text(consumer.get("system")),
                        text(consumer.get("plan_reference"))));
            }
            Handling handling = null;
            if (!row.get("handling").isJsonNull()) {
                JsonObject data = closed(row.get("handling"), Set.of("action", "discard_allowed", "hazardous",
                        "containment", "treatment_route"));
                handling = new Handling(enumeration(Action.class, data.get("action")),
                        bool(data.get("discard_allowed")), bool(data.get("hazardous")),
                        optionalResource(data.get("containment")), optionalText(data.get("treatment_route")));
            }
            Recycling recycling = null;
            if (!row.get("recycling").isJsonNull()) {
                JsonObject data = closed(row.get("recycling"), Set.of("route", "planned_tier"));
                recycling = new Recycling(optionalText(data.get("route")), optionalTier(data.get("planned_tier")));
            }
            ResourceMetadata metadata = new ResourceMetadata(enumeration(ResourceClass.class, row.get("resource_class")),
                    enumeration(SideStreamClass.class, row.get("side_stream_class")),
                    optionalTier(row.get("first_use_tier")), optionalTier(row.get("first_renewable_tier")),
                    optionalText(row.get("canonical_route")), future, handling, recycling,
                    optionalResource(row.get("originating_catalyst")), optionalText(row.get("uncertainty")));
            Map<String, String> sources = new TreeMap<>();
            row.getAsJsonObject("sources").entrySet().forEach(source -> sources.put(source.getKey(), text(source.getValue())));
            if (resources.put(resource, new Entry(metadata, references(row.get("producers")),
                    references(row.get("consumers")), sources)) != null) {
                throw new IllegalArgumentException("Duplicate guidance resource");
            }
        }
        Document document = new Document(schema, text(root.get("content_sha256")), resources);
        if (!write(document).equals(json)) {
            throw new IllegalArgumentException("Resource guidance is not the complete canonical generated document");
        }
        return document;
    }

    private static JsonArray payload(Map<Resource, Entry> resources) {
        JsonArray rows = new JsonArray();
        new TreeMap<>(resources).forEach((resource, entry) -> {
            ResourceMetadata metadata = entry.metadata();
            Handling handling = metadata.handling();
            Recycling recycling = metadata.recycling();
            JsonArray future = new JsonArray();
            metadata.futureConsumers().forEach(consumer -> future.add(object("tier", consumer.tier(),
                    "system", consumer.system(), "plan_reference", consumer.planReference())));
            rows.add(object("resource", identity(resource), "resource_class", lower(metadata.resourceClass()),
                    "side_stream_class", lower(metadata.sideStreamClass()), "first_use_tier", metadata.firstUseTier(),
                    "first_renewable_tier", metadata.firstRenewableTier(), "canonical_route", metadata.canonicalRoute(),
                    "future_consumers", future, "handling", handling == null ? null : object(
                            "action", lower(handling.action()), "discard_allowed", handling.discardAllowed(),
                            "hazardous", handling.hazardous(), "containment", identity(handling.containment()),
                            "treatment_route", handling.treatmentRoute()),
                    "recycling", recycling == null ? null : object("route", recycling.route(),
                            "planned_tier", recycling.plannedTier()),
                    "originating_catalyst", identity(metadata.originatingCatalyst()), "uncertainty", metadata.uncertainty(),
                    "producers", references(entry.producers()), "consumers", references(entry.consumers()),
                    "sources", entry.sources()));
        });
        return rows;
    }

    private static JsonArray references(List<RouteReference> references) {
        JsonArray array = new JsonArray();
        references.forEach(reference -> array.add(object("route", reference.route(), "source", reference.source(),
                "via", reference.via(), "kind", lower(reference.kind()), "certainty", lower(reference.certainty()),
                "unconditional", reference.unconditional(), "unlock_tier", reference.unlockTier(),
                "optional", reference.optional(), "discharged", reference.discharged())));
        return array;
    }

    private static List<RouteReference> references(JsonElement value) {
        List<RouteReference> references = new ArrayList<>();
        for (JsonElement element : array(value)) {
            JsonObject data = closed(element, Set.of("route", "source", "via", "kind", "certainty", "unconditional",
                    "unlock_tier", "optional", "discharged"));
            RouteReference reference = new RouteReference(text(data.get("route")), text(data.get("source")),
                    text(data.get("via")), enumeration(ReferenceKind.class, data.get("kind")),
                    enumeration(Certainty.class, data.get("certainty")), bool(data.get("unconditional")),
                    optionalTier(data.get("unlock_tier")), data.get("optional").isJsonNull() ? null : bool(data.get("optional")),
                    bool(data.get("discharged")));
            if (references.contains(reference)) {
                throw new IllegalArgumentException("Duplicate guidance route reference");
            }
            references.add(reference);
        }
        return List.copyOf(references);
    }

    private static JsonElement identity(Resource resource) {
        return resource == null ? JsonNull.INSTANCE : object("kind", lower(resource.kind()), "id", resource.id(),
                "rating", resource.rating(), "registry", resource.registry());
    }

    private static Resource optionalResource(JsonElement value) {
        return value.isJsonNull() ? null : resource(value);
    }

    private static Resource resource(JsonElement value) {
        JsonObject identity = closed(value, Set.of("kind", "id", "rating", "registry"));
        return new Resource(enumeration(Kind.class, identity.get("kind")), text(identity.get("id")),
                integer(identity.get("rating")), text(identity.get("registry")));
    }

    private static JsonObject closed(JsonElement value, Set<String> fields) {
        JsonObject object = value.getAsJsonObject();
        if (!object.keySet().equals(fields)) {
            throw new IllegalArgumentException("Missing or unknown resource guidance fields");
        }
        return object;
    }

    private static JsonArray array(JsonElement value) {
        return value.getAsJsonArray();
    }

    private static String text(JsonElement value) {
        if (!value.isJsonPrimitive() || !value.getAsJsonPrimitive().isString() || value.getAsString().isBlank()) {
            throw new IllegalArgumentException("Expected resource guidance text");
        }
        return value.getAsString();
    }

    private static String optionalText(JsonElement value) {
        return value.isJsonNull() ? null : text(value);
    }

    private static int integer(JsonElement value) {
        if (!value.isJsonPrimitive() || !value.getAsJsonPrimitive().isNumber()) {
            throw new IllegalArgumentException("Expected resource guidance integer");
        }
        return value.getAsBigDecimal().intValueExact();
    }

    private static Integer optionalTier(JsonElement value) {
        if (value.isJsonNull()) {
            return null;
        }
        int tier = integer(value);
        if (tier < 0 || tier > 15) {
            throw new IllegalArgumentException("Invalid declared tier");
        }
        return tier;
    }

    private static boolean bool(JsonElement value) {
        if (!value.isJsonPrimitive() || !value.getAsJsonPrimitive().isBoolean()) {
            throw new IllegalArgumentException("Expected resource guidance boolean");
        }
        return value.getAsBoolean();
    }

    private static <T extends Enum<T>> T enumeration(Class<T> type, JsonElement value) {
        return value.isJsonNull() ? null : Enum.valueOf(type, text(value).toUpperCase(Locale.ROOT));
    }

    private static String lower(Enum<?> value) {
        return value == null ? null : value.name().toLowerCase(Locale.ROOT);
    }

    private static JsonObject object(Object... pairs) {
        JsonObject object = new JsonObject();
        for (int index = 0; index < pairs.length; index += 2) {
            object.add((String) pairs[index], JSON.toJsonTree(pairs[index + 1]));
        }
        return object;
    }

    private static String fingerprint(JsonArray resources) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                    .digest(JSON.toJson(resources).getBytes(StandardCharsets.UTF_8)));
        } catch (NoSuchAlgorithmException impossible) {
            throw new IllegalStateException(impossible);
        }
    }
}
